CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255), email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255), phone VARCHAR(255), document VARCHAR(255), address VARCHAR(255),
 role VARCHAR(255), active BOOLEAN NOT NULL
);
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku VARCHAR(255) UNIQUE, name VARCHAR(255), category VARCHAR(255), presentation VARCHAR(255),
 description VARCHAR(2000), price NUMERIC(38,2), published BOOLEAN NOT NULL
);
CREATE TABLE lots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT NOT NULL REFERENCES products(id), code VARCHAR(255), warehouse VARCHAR(255),
 expiry DATE, quantity NUMERIC(38,2), reserved NUMERIC(38,2), status VARCHAR(255), version BIGINT NOT NULL
);
CREATE TABLE customer_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT REFERENCES accounts(id), status VARCHAR(255), address VARCHAR(255),
 total NUMERIC(38,2), version BIGINT NOT NULL
);
CREATE TABLE order_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT REFERENCES customer_orders(id), product_id BIGINT REFERENCES products(id),
 quantity NUMERIC(38,2), unit_price NUMERIC(38,2)
);
CREATE TABLE production_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id BIGINT REFERENCES products(id), planned NUMERIC(38,2), route VARCHAR(255), status VARCHAR(255)
);
CREATE TABLE allocations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT REFERENCES customer_orders(id), lot_id BIGINT REFERENCES lots(id), quantity NUMERIC(38,2)
);
CREATE INDEX idx_lots_product_expiry ON lots(product_id, expiry);
CREATE INDEX idx_orders_customer ON customer_orders(customer_id);
CREATE INDEX idx_lines_order ON order_lines(order_id);
CREATE INDEX idx_allocations_order ON allocations(order_id);
