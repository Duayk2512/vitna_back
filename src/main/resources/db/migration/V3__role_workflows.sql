CREATE TABLE production_steps (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 production_id BIGINT NOT NULL REFERENCES production_orders(id),
 name VARCHAR(255), status VARCHAR(255), step_position INTEGER NOT NULL,
 started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ,
 CONSTRAINT uk_production_step_position UNIQUE(production_id, step_position)
);
INSERT INTO production_steps (production_id,name,status,step_position)
SELECT p.id,COALESCE(NULLIF(TRIM(s.name),''),'Producción'),'PENDIENTE',s.position::integer
FROM production_orders p
CROSS JOIN LATERAL regexp_split_to_table(COALESCE(NULLIF(p.route,''),'Producción'),'\s*(→|->|>|,)\s*') WITH ORDINALITY AS s(name,position);
